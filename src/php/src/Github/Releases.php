<?php

declare(strict_types=1);

namespace Simtabi\ServerInfraWorkbench\Github;

use Simtabi\ServerInfraWorkbench\Exception\NotFoundException;
use Simtabi\ServerInfraWorkbench\Http\Endpoint;
use Simtabi\ServerInfraWorkbench\Http\Transport;
use Simtabi\ServerInfraWorkbench\Safety\PendingAction;
use Simtabi\ServerInfraWorkbench\Support\Item;
use Simtabi\ServerInfraWorkbench\Support\Validate;

/** Releases (and the tags they create). */
final readonly class Releases
{
    private Endpoint $api;

    public function __construct(Transport $transport, private Repository $repo)
    {
        $this->api = new Endpoint($transport, 'release', $repo->path('releases'), new GithubPaginator, [
            'id' => 'id', 'tag' => 'tag_name', 'name' => 'name', 'draft' => 'draft', 'prerelease' => 'prerelease',
            'publishedAt' => 'published_at', 'url' => 'html_url', 'assets' => static fn (array $r): int => count((array) ($r['assets'] ?? [])),
        ], null, ['per_page' => 100]);
    }

    /** @return list<Item> */
    public function list(int $limit = 30): array
    {
        return array_slice($this->api->list(), 0, max(1, $limit));
    }

    /** The newest published, non-draft, non-prerelease release. */
    public function latest(): Item
    {
        try {
            return $this->api->get('latest');
        } catch (NotFoundException) {
            throw new NotFoundException(sprintf('%s has no published release yet', $this->repo), 'GitHub', 404);
        }
    }

    /**
     * Idempotent by tag. Notes are generated by GitHub from merged PRs when none are given.
     *
     * @return PendingAction<Item>
     */
    public function create(string $tag, ?string $target = null, ?string $name = null, ?string $notes = null, bool $draft = false, bool $prerelease = false): PendingAction
    {
        $tag = Workflows::ref($tag);
        foreach ($this->list(100) as $release) {
            if ($release->string('tag') === $tag) {
                return $this->api->noop('create release', "{$tag} (exists: {$release->string('url')})", $release);
            }
        }
        $body = array_filter([
            'tag_name' => $tag, 'target_commitish' => $target === null ? null : Workflows::ref($target), 'name' => $name === null ? null : Validate::label($name, 'release name'),
            'body' => $notes, 'generate_release_notes' => $notes === null, 'draft' => $draft, 'prerelease' => $prerelease,
        ], static fn (mixed $v): bool => $v !== null);

        return $this->api->create($body, "{$tag} on {$this->repo}".($draft ? ' (draft)' : ''), $draft ? null : 'published at once: watchers are notified and the tag is created');
    }

    /**
     * Destructive. The git tag stays (delete it separately if you mean to).
     *
     * @return PendingAction<bool>
     */
    public function delete(int|string $id): PendingAction
    {
        return $this->api->delete(Validate::id($id, 'release id'), "{$id} on {$this->repo}", 'its assets are deleted; the git tag is kept');
    }
}
